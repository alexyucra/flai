"""
Form Agent - Especialista em criação de formulários
"""
from pathlib import Path
from typing import Dict, List, Optional
from flai.cli.console.console import console

class FormAgent:
    def __init__(self, project_path: Optional[Path] = None):
        self.project_path = project_path or Path.cwd()
    
    def create(self, form_name: str, fields: Optional[List[str]] = None) -> Dict:
        console.print(f"[bold cyan]📝 Criando formulário: {form_name}[/bold cyan]")
        if fields:
            console.print(f"[dim]Campos: {', '.join(fields)}[/dim]")
        
        # Se não houver campos, usa padrão
        if not fields:
            fields = ["nome", "email"]
        
        form_path = self.project_path / "forms" / f"{form_name}.py"
        form_path.parent.mkdir(parents=True, exist_ok=True)
        
        # Construindo o código linha por linha para evitar problemas de f-string
        lines = []
        lines.append('\"\"\"')
        lines.append(f'Form {form_name.capitalize()}')
        lines.append('Auto-generated by FLAI')
        lines.append('\"\"\"')
        lines.append('import flet as ft')
        lines.append('')
        lines.append(f'class {form_name.capitalize()}Form(ft.UserControl):')
        lines.append('    def __init__(self, on_submit=None):')
        lines.append('        super().__init__()')
        lines.append('        self.on_submit = on_submit')
        lines.append('')
        lines.append('    def build(self):')
        
        # Adiciona campos
        for field in fields:
            field_name = field.lower().replace(" ", "_")
            lines.append(f'        self.{field_name}_field = ft.TextField(label="{field.capitalize()}")')
        
        lines.append('')
        lines.append('        self.submit_button = ft.ElevatedButton("Enviar", on_click=self._on_submit)')
        lines.append('')
        lines.append('        return ft.Column([')
        
        for field in fields:
            field_name = field.lower().replace(" ", "_")
            lines.append(f'            self.{field_name}_field,')
        
        lines.append('            self.submit_button')
        lines.append('        ])')
        lines.append('')
        lines.append('    def _on_submit(self, e):')
        lines.append('        if self.on_submit:')
        lines.append('            data = {')
        
        for field in fields:
            field_name = field.lower().replace(" ", "_")
            lines.append(f'                "{field_name}": self.{field_name}_field.value,')
        
        lines.append('            }')
        lines.append('            self.on_submit(data)')
        
        content = '\n'.join(lines)
        form_path.write_text(content)
        
        console.print(f"[green]✅ Formulário '{form_name}' criado em: {form_path}[/green]")
        return {"success": True, "form": form_name, "message": f"Formulário '{form_name}' criado"}